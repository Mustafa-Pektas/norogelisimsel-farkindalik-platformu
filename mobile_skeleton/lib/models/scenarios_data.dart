import 'package:flutter/material.dart';

class ScenarioModel {
  final String code;
  final String title;
  final String category;
  final String ageRange;
  final int minAgeMonths;
  final int maxAgeMonths;
  final String antecedent;
  final String instruction;
  final String measurementCriteria;
  final String riskThreshold;
  final Map<String, String> ageBreakdowns;
  final List<ScenarioBranchModel> branches;
  final Map<String, List<ScenarioBranchModel>> ageSpecificBranches;
  final Map<String, String>? videoAssets;

  const ScenarioModel({
    required this.code,
    required this.title,
    required this.category,
    required this.ageRange,
    required this.minAgeMonths,
    required this.maxAgeMonths,
    required this.antecedent,
    required this.instruction,
    required this.measurementCriteria,
    required this.riskThreshold,
    required this.ageBreakdowns,
    required this.branches,
    required this.ageSpecificBranches,
    this.videoAssets,
  });

  List<ScenarioBranchModel> getBranchesForAge(String ageGroup) {
    if (ageSpecificBranches.containsKey(ageGroup)) {
      return ageSpecificBranches[ageGroup]!;
    }
    return branches;
  }
}

